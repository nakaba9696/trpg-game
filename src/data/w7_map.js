// W7：地図に描く道の曲がり角（D.W5_MAP.via）と、地図の形の直し。data/w5_map.js のあとに読まれる。
// 道はまっすぐ引くと、ほかの場所の印の上を通ったり、別の道と交わったりして「そこからも行ける」ように見える。
// そういう道だけ、角を足して曲げる。キーは両端の id を名前順に「a|b」（船は頭に「~」）、角は a から b への順。座標は場所の x・y と同じ。
// 描く線＝links・sea にある道、ほかの印の上を通らない、道どうしが町の外で交わらない、船は海の上を行く、を tests/checks/w7_map.mjs が確かめる。
// レーン W（W7）
(function (G) {
  const D = G.data;
  if (!D.W5_MAP) return;
  D.W5_MAP.via = Object.assign(D.W5_MAP.via || {}, {
    // 断界山脈 → 灰の荒野：まっすぐだと狩り場の町ナグリスの上を通っていた。尾根に沿って東へ越える
    "mountains|wasteland": [[86, 33], [92, 42]],
    // ブランデール → 港町：まっすぐだと鐘撞きの丘の上を通っていた。南の低地を回る
    "karna|nerva": [[38, 68]],
    // ブランデール → 毒沼：まっすぐだと迷いの森の上を通り、森 → 遺構の道と交わっていた。森の東を回る
    "karna|swamp": [[58, 63]],
    // 船：陸の上を描かないように、海を回る
    "~nerva|yakumo": [[20, 79], [12, 82]],
    "~nerva|w3_carmeland": [[20, 80], [9, 81], [1, 72], [-5, 55], [-4, 43]],
    "~w3_carmeland|w7_eisenvan": [[-4, 34], [-6, 20]],
    "~nerva|w7_volera": [[21, 80], [24, 88], [25, 101], [42, 105], [66, 101]],
  });
  // リグノアの湖：市の都ヴァルミリアを北へ移したので、道が湖を渡らないように、森と湖の都リグノアの西へ
  const lake = D.W5_MAP.lakes.find((e) => e.x === 24.5 && e.y === 19.5);
  if (lake) Object.assign(lake, { x: 16.5, y: 22 });
  // シェルアークの島（W7c の町）：網の島・霧鐘の島・真珠採りの島。名の無い小島を町の島に広げる（大陸と島の都のあいだの船の道にはかからないように）
  const isl = D.W5_MAP.islands;
  const grow = (x, y, to) => { const e = isl.find((i) => i.x === x && i.y === y); if (e) Object.assign(e, to); else isl.push(to); };
  grow(7, 101, { x: 8, y: 98, rx: 2.6, ry: 2.2, rot: 0.2 });     // 網の島カラヴ
  grow(-4, 88, { x: 0, y: 87, rx: 2.6, ry: 2.4, rot: 0.5 });     // 霧鐘の島ミストラ
  grow(60, 101, { x: 13.5, y: 99.5, rx: 2.6, ry: 1.9, rot: 0.2 }); // 真珠採りの島ヨナ（南の海の名の無い小島を移す）
})(globalThis.G = globalThis.G || {});
